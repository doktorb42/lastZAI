#!/usr/bin/env python3
"""Create a signed-APK-ready copy with one or more asset entries replaced.

The source APK is never modified.  All non-signature entries retain their
original ZIP compression method and metadata; APK v1 signatures are omitted
because the resulting copy must be signed afresh.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import shutil
import zipfile
from pathlib import Path


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def digest_file(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(block)
    return hasher.hexdigest()


def is_signature_entry(name: str) -> bool:
    upper = name.upper()
    if not upper.startswith("META-INF/"):
        return False
    leaf = upper.rsplit("/", 1)[-1]
    return leaf == "MANIFEST.MF" or leaf.endswith((".SF", ".RSA", ".DSA", ".EC"))


def clone_info(info: zipfile.ZipInfo) -> zipfile.ZipInfo:
    cloned = copy.copy(info)
    # These values belong to the old ZIP's local-header placement and must be
    # regenerated by ZipFile for the new output archive.
    cloned.header_offset = 0
    cloned.CRC = None
    cloned.compress_size = 0
    cloned.file_size = 0
    return cloned


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apk", required=True, type=Path)
    parser.add_argument("--replacement", type=Path, help="Compatibility form: replacement file used with --entry.")
    parser.add_argument("--entry", help="Compatibility form: APK entry used with --replacement.")
    parser.add_argument("--replace", action="append", default=[], metavar="ENTRY=FILE", help="Repeat for each APK entry to replace.")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    source = args.apk.resolve()
    output = args.output.resolve()
    requested: list[tuple[str, Path]] = []
    if (args.replacement is None) != (args.entry is None):
        raise SystemExit("--replacement and --entry must be provided together.")
    if args.replacement is not None:
        requested.append((args.entry, args.replacement.resolve()))
    for value in args.replace:
        if "=" not in value:
            raise SystemExit(f"Invalid --replace value {value!r}; expected ENTRY=FILE.")
        entry, filename = value.split("=", 1)
        if not entry or not filename:
            raise SystemExit(f"Invalid --replace value {value!r}; expected ENTRY=FILE.")
        requested.append((entry, Path(filename).resolve()))
    if not requested:
        raise SystemExit("Provide --replace ENTRY=FILE (or legacy --entry/--replacement).")
    targets: dict[str, bytes] = {}
    for entry, replacement in requested:
        if entry in targets:
            raise SystemExit(f"Duplicate replacement target: {entry}")
        if not replacement.is_file():
            raise SystemExit(f"Replacement input is missing: {replacement}")
        if output == replacement:
            raise SystemExit("Refusing to overwrite a replacement input.")
        targets[entry] = replacement.read_bytes()
    if output == source or not source.is_file():
        raise SystemExit("Source APK is missing or output would overwrite it.")

    print(f"source      : {source}")
    print(f"source bytes: {source.stat().st_size}")
    for entry, payload in targets.items():
        print(f"replacement entry: {entry}")
        print(f"payload bytes: {len(payload)}")
        print(f"payload sha256: {digest(payload)}")

    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(source, "r") as zin:
        infos = zin.infolist()
        source_infos: dict[str, zipfile.ZipInfo] = {}
        for entry in targets:
            matches = [info for info in infos if info.filename == entry]
            if len(matches) != 1:
                raise SystemExit(f"Expected exactly one target ZIP entry for {entry}, found {len(matches)}.")
            source_infos[entry] = matches[0]
            original = zin.read(matches[0])
            print(f"target {entry} method: {matches[0].compress_type} (0=stored, 8=deflated)")
            print(f"target original bytes: {len(original)}")
            print(f"target original sha256: {digest(original)}")

        with zipfile.ZipFile(output, "w", allowZip64=True) as zout:
            written = 0
            skipped = 0
            for info in infos:
                if is_signature_entry(info.filename):
                    skipped += 1
                    continue
                cloned = clone_info(info)
                with zout.open(cloned, "w", force_zip64=info.file_size >= zipfile.ZIP64_LIMIT) as dst:
                    if info.filename in targets:
                        dst.write(targets[info.filename])
                    else:
                        with zin.open(info, "r") as src:
                            shutil.copyfileobj(src, dst, length=1024 * 1024)
                written += 1
                if written % 250 == 0:
                    print(f"copied entries: {written}/{len(infos)}", flush=True)

    with zipfile.ZipFile(output, "r") as verify:
        for entry, payload in targets.items():
            result = verify.read(entry)
            info = verify.getinfo(entry)
            if result != payload:
                raise SystemExit(f"Round-trip verification failed for {entry}.")
            if info.compress_type != source_infos[entry].compress_type:
                raise SystemExit(f"Replacement ZIP compression method changed unexpectedly for {entry}.")
        if any(is_signature_entry(x.filename) for x in verify.infolist()):
            raise SystemExit("Stale APK v1 signature entries remain in output.")
    print(f"output      : {output}")
    print(f"output bytes: {output.stat().st_size}")
    print(f"output sha256: {digest_file(output)}")
    print(f"entries written: {written}; signatures removed: {skipped}")
    print("OK: replacement entry passed exact ZIP round-trip verification.")


if __name__ == "__main__":
    main()
